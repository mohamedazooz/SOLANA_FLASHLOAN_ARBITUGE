def project(t):
    a = abs(t)
    r = C[0] if a & 1 else 1 << 128
    for i in range(1, 19):
        if a & (1 << i):
            r = (r * C[i]) >> 128
    if t > 0:
        r = ((1 << 256) - 1) // r
    return r >> 64


